"""Export native shield block values without replacing the embedded item catalog.

Usage: python tools/build_shield_block.py --database SNAPSHOT.sqlite --verified-at YYYY-MM-DD
The input is the uncompressed Tortoise database. Source work files stay in tools/work/.
"""
import argparse
import hashlib
import json
from pathlib import Path
import re
import sqlite3


ROOT = Path(__file__).resolve().parents[1]


def catalog_shields(root):
    found = set()
    pattern = re.compile(r'^I\[(\d+)\]=\{(?:"(?:[^"\\]|\\.)*"),\d+,"SHIELD"', re.M)
    for path in (Path(root) / "Data/AshenDB/Data/Items").glob("Items_*.lua"):
        found.update(int(match.group(1)) for match in pattern.finditer(path.read_text(encoding="utf-8")))
    if not found:
        raise ValueError("No shield records found in the embedded catalog")
    return found


def build(database, output, verified_at, root=ROOT):
    database, output = Path(database), Path(output)
    if not database.is_file():
        raise ValueError("Input database does not exist")
    if not re.fullmatch(r"\d{4}-\d{2}-\d{2}", verified_at):
        raise ValueError("Verification date must have the form YYYY-MM-DD")
    digest = hashlib.sha256(database.read_bytes()).hexdigest()
    version = digest[:12]
    connection = sqlite3.connect(database.as_uri() + "?mode=ro", uri=True)
    try:
        columns = {row[1] for row in connection.execute("pragma table_info(items)")}
        if not {"entry", "inventory_type", "block"}.issubset(columns):
            raise ValueError("Input items table must retain entry, inventory_type and native block")
        rows = connection.execute("select entry, block from items where inventory_type=14 order by entry").fetchall()
    finally:
        connection.close()
    native = {}
    for item_id, value in rows:
        if value is None or isinstance(value, str) or value < 0 or value != int(value):
            raise ValueError("Invalid native shield block for item " + str(item_id))
        native[int(item_id)] = int(value)
    expected = catalog_shields(root)
    missing = expected - native.keys()
    if missing:
        raise ValueError("Source lacks embedded shield IDs: " + ", ".join(map(str, sorted(missing))))
    url = "https://cdn.jsdelivr.net/gh/Xian55/tortoise-db-viewer@cdn-v" + version + "/data/tortoise.sqlite.br"
    metadata = {
        "source": "Tortoise-WoW", "sourceVersion": version, "sqliteSha256": digest,
        "sourceUrl": url, "verifiedAt": verified_at, "count": len(expected),
    }
    lines = ["-- Native shield block only; Equip block-value bonuses remain separate.",
             "-- Generated by tools/build_shield_block.py; see docs/data-sources-1.0.2.md.",
             "AshenBuilds = AshenBuilds or {}", "AshenBuilds.ShieldBlockMeta={" +
             ",".join(key + "=" + (str(value) if isinstance(value, int) else json.dumps(value))
                      for key, value in sorted(metadata.items())) + "}",
             "AshenBuilds.ShieldBaseBlock={"]
    lines.extend("  [" + str(item_id) + "]=" + str(native[item_id]) + "," for item_id in sorted(expected))
    lines.append("}")
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
    return metadata


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--database", type=Path, required=True)
    parser.add_argument("--verified-at", required=True)
    parser.add_argument("--output", type=Path, default=ROOT / "Data/ShieldBlock.lua")
    args = parser.parse_args()
    try:
        metadata = build(args.database.resolve(), args.output, args.verified_at)
    except (ValueError, OSError, sqlite3.DatabaseError) as exc:
        parser.error(str(exc))
    print("Exported", metadata["count"], "native shield block values from", metadata["sourceVersion"])


if __name__ == "__main__":
    main()
